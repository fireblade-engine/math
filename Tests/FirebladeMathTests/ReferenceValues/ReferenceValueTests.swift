// Checks that this platform reproduces the reference values recorded on the reference
// platform (macOS, default traits) for every registered function, up to rounding.
//
// Regenerate ReferenceData.swift after intentionally changing results or adding functions:
//     make reference-values
// which runs this suite with FRB_MATH_REFERENCE_OUTPUT set to the data file path.

import Foundation
import Testing

struct ReferenceValueTests {
    static let outputPath = ProcessInfo.processInfo.environment["FRB_MATH_REFERENCE_OUTPUT"]

    @Test(.enabled(if: outputPath == nil, "Generating reference values instead"))
    func everyFunctionMatchesTheReferenceValues() throws {
        let recorded = try ReferenceData.parse()
        let registered = Dictionary(uniqueKeysWithValues: ReferenceRegistry.all.map { ($0.key, $0) })

        let unrecorded = Set(registered.keys).subtracting(recorded.keys).sorted()
        #expect(unrecorded.isEmpty, "Registered functions without reference values (run `make reference-values`): \(unrecorded)")
        let stale = Set(recorded.keys).subtracting(registered.keys).sorted()
        #expect(stale.isEmpty, "Reference values for functions that are not registered: \(stale)")

        var checkedCases = 0
        for key in registered.keys.sorted() {
            guard let function = registered[key], let cases = recorded[key] else { continue }
            var mismatches: [String] = []
            for (inputs, expected) in cases {
                checkedCases += 1
                let actual = function.evaluate(inputs)
                if let problem = referenceMismatch(
                    inputs: inputs,
                    actual: actual,
                    expected: expected,
                    accuracy: function.accuracy,
                    singlePrecision: function.singlePrecisionResult
                ) {
                    mismatches.append("inputs \(inputs): \(problem)")
                }
            }
            #expect(
                mismatches.isEmpty,
                "\(key) [\(function.accuracy)]: \(mismatches.count) of \(cases.count) cases differ, e.g. \(mismatches.prefix(3).joined(separator: "; "))"
            )
        }
        #expect(checkedCases > 0)
    }

    @Test(.enabled(if: outputPath != nil, "Set FRB_MATH_REFERENCE_OUTPUT to regenerate"))
    func generateReferenceValues() throws {
        let path = try #require(Self.outputPath)
        var lines: [String] = []
        for (index, function) in ReferenceRegistry.all.sorted(by: { $0.key < $1.key }).enumerated() {
            let cases = function.generateInputs(seed: 0xF1BE_0000 &+ UInt64(index) &* 0x1_0000).map { inputs in
                ReferenceData.encode(inputs) + "|" + ReferenceData.encode(function.evaluate(inputs))
            }
            lines.append(function.key + "\t" + cases.joined(separator: ";"))
        }
        try ReferenceData.render(lines).write(toFile: path, atomically: true, encoding: .utf8)
    }
}

// MARK: - Data format

extension ReferenceData {
    /// One line per function: `key<TAB>case;case;...`, a case is `inputs|outputs`, values are
    /// comma-separated Double bit patterns in hexadecimal (exact, platform independent).
    static func parse() throws -> [String: [(inputs: [Double], outputs: [Double])]] {
        var result: [String: [(inputs: [Double], outputs: [Double])]] = [:]
        for line in values.split(separator: "\n") where !line.isEmpty {
            let parts = line.split(separator: "\t", maxSplits: 1)
            guard parts.count == 2 else { throw DataError.malformed(String(line.prefix(80))) }
            result[String(parts[0])] = try parts[1].split(separator: ";").map { testCase in
                let sides = testCase.split(separator: "|", omittingEmptySubsequences: false)
                guard sides.count == 2 else { throw DataError.malformed(String(testCase.prefix(80))) }
                return (try decode(sides[0]), try decode(sides[1]))
            }
        }
        return result
    }

    static func encode(_ values: [Double]) -> String {
        values.map { String($0.bitPattern, radix: 16) }.joined(separator: ",")
    }

    static func decode(_ text: Substring) throws -> [Double] {
        try text.split(separator: ",").map { field in
            guard let bits = UInt64(field, radix: 16) else { throw DataError.malformed(String(field)) }
            return Double(bitPattern: bits)
        }
    }

    static func render(_ lines: [String]) -> String {
        """
        //
        //  ReferenceData.swift
        //  FirebladeMathTests
        //

        // Generated by `make reference-values` on the reference platform (macOS, default traits).
        // Do not edit by hand. Format: see ReferenceValueTests.swift.

        // swiftlint:disable file_length line_length

        enum ReferenceData {
            static let values = \"\"\"
        \(lines.joined(separator: "\n"))
        \"\"\"
        }

        // swiftlint:enable file_length line_length

        """
    }

    enum DataError: Error {
        case malformed(String)
    }
}
